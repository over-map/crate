#!/usr/bin/env python3
"""Generate app/.../ui/theme/Tokens.kt from ios/Design/tokens.json (the design handoff's source of truth, shared with
iOS's gen_tokens.py). Run after replacing tokens.json:  python3 android/tools/gen_tokens.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ANDROID = Path(__file__).resolve().parents[1]
TOKENS = ANDROID.parent / "ios" / "Design" / "tokens.json"
OUT = ANDROID / "app" / "src" / "main" / "kotlin" / "com" / "overmap" / "crate" / "ui" / "theme" / "Tokens.kt"

WEIGHT = {"regular": "FontWeight.Normal", "medium": "FontWeight.Medium", "semibold": "FontWeight.SemiBold",
          "bold": "FontWeight.Bold"}


def argb(h: str) -> str:
    return "Color(0xFF" + h.lstrip("#").upper() + ")"


def ident(s: str) -> str:
    parts = [p for p in re.split(r"[^a-zA-Z0-9]+", s) if p]
    return parts[0][0].lower() + parts[0][1:] + "".join(p[0].upper() + p[1:] for p in parts[1:])


def enum_case(s: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", ident(s)).upper()


def main() -> None:
    t = json.loads(TOKENS.read_text())
    L = [
        "// Generated by android/tools/gen_tokens.py from ios/Design/tokens.json. Do not edit by hand.",
        "@file:Suppress(\"MagicNumber\")",
        "",
        "package com.overmap.crate.ui.theme",
        "",
        "import androidx.compose.runtime.Immutable",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.text.TextStyle",
        "import androidx.compose.ui.text.font.FontFamily",
        "import androidx.compose.ui.text.font.FontWeight",
        "import androidx.compose.ui.unit.dp",
        "import androidx.compose.ui.unit.sp",
        "",
    ]
    colors = t["color"]
    L.append("/** Semantic colours (design-system §2). Read them through `CrateTheme.colors`. */")
    L.append("@Immutable")
    L.append("data class CrateColors(")
    for name, c in colors.items():
        L.append(f"    /** {c.get('use', '')} */".replace("/**  */", "/** */"))
        L.append(f"    val {name}: Color,")
    L.append("    val isDark: Boolean,")
    L.append(")")
    L.append("")
    for mode in ("dark", "light"):
        L.append(f"val {mode.capitalize()}CrateColors = CrateColors(")
        for name, c in colors.items():
            L.append(f"    {name} = {argb(c[mode])},")
        L.append(f"    isDark = {'true' if mode == 'dark' else 'false'},")
        L.append(")")
        L.append("")

    fams = {k: v for k, v in t["family"].items() if isinstance(v, dict) and "shades" in v and k != "none"}
    neutral = (t["family"].get("none") or {}).get("shades", {}).get("base")
    L.append("/** Chip shade of a style inside its family (StyleShade). */")
    L.append("enum class StyleShade {")
    L.append("    LIGHT, BASE, DEEP;")
    L.append("")
    L.append("    companion object {")
    L.append("        /** `[light, base, deep][fnv1a32(utf8(canonical)) % 3]`, identical to CrateKit's `StyleShade.of`. */")
    L.append("        fun of(canonicalStyle: String): StyleShade = entries[(fnv1a32(canonicalStyle) % 3u).toInt()]")
    L.append("")
    L.append("        /** 32-bit FNV-1a over the UTF-8 bytes (offset basis 2166136261, prime 16777619). */")
    L.append("        fun fnv1a32(text: String): UInt {")
    L.append("            var hash = 2166136261u")
    L.append("            for (byte in text.encodeToByteArray()) {")
    L.append("                hash = hash xor byte.toUByte().toUInt()")
    L.append("                hash *= 16777619u")
    L.append("            }")
    L.append("            return hash")
    L.append("        }")
    L.append("    }")
    L.append("}")
    L.append("")
    L.append("/** The 17 style families (\"Genre\" in the UI). `data` is the id in library.json. */")
    L.append("enum class Family(val data: String, val displayName: String) {")
    for k, f in fams.items():
        L.append(f"    {enum_case(k)}(\"{f['data']}\", \"{f['name']}\"),")
    L.append("    NONE(\"\", \"No genre\");")
    L.append("")
    L.append("    companion object {")
    L.append("        fun of(data: String?): Family = entries.firstOrNull { it.data == data && it != NONE } ?: NONE")
    L.append("    }")
    L.append("}")
    L.append("")
    L.append("/** Chip fill for a family in one of its shades. */")
    L.append("fun familyColor(family: Family, shade: StyleShade = StyleShade.BASE, dark: Boolean = true): Color = when (family) {")
    for k, f in fams.items():
        s = f["shades"]
        L.append(f"    Family.{enum_case(k)} -> when (shade) {{")
        for sh in ("light", "base", "deep"):
            L.append(f"        StyleShade.{sh.upper()} -> if (dark) {argb(s[sh]['dark'])} else {argb(s[sh]['light'])}")
        L.append("    }")
    if neutral and "dark" in neutral:
        L.append(f"    Family.NONE -> if (dark) {argb(neutral['dark'])} else {argb(neutral.get('light', neutral['dark']))}")
    else:
        L.append("    Family.NONE -> Color(0xFFC5BBBD)")
    L.append("}")
    L.append("")
    L.append("/** Outline colour of a family (removed style in Edit). */")
    L.append("fun familyOutline(family: Family, dark: Boolean = true): Color = when (family) {")
    for k, f in fams.items():
        o = f["outline"]
        L.append(f"    Family.{enum_case(k)} -> if (dark) {argb(o['dark'])} else {argb(o['light'])}")
    L.append("    Family.NONE -> Color(0xFF8A8A90)")
    L.append("}")
    L.append("")
    L.append("/** Energy meter colour for levels 1–10. */")
    L.append("fun energyColor(level: Int, dark: Boolean = true): Color = when (level.coerceIn(1, 10)) {")
    for e in t["energy"]:
        L.append(f"    {e['level']} -> if (dark) {argb(e['dark'])} else {argb(e['light'])}")
    L.append("    else -> Color.Gray")
    L.append("}")
    L.append("")
    L.append("/** Camelot badge fill (`code` like \"8A\"). */")
    L.append("fun camelotColor(code: String, dark: Boolean = true): Color = when (code) {")
    for code, c in t["camelot"].items():
        L.append(f"    \"{code}\" -> if (dark) {argb(c['dark'])} else {argb(c['light'])}")
    L.append("    else -> Color.Gray")
    L.append("}")
    L.append("")
    L.append("/** Preset tile colours. */")
    L.append("enum class PresetColor {")
    L.append("    " + ", ".join(k.upper() for k in t["presetColor"]) + ";")
    L.append("")
    L.append("    fun tile(dark: Boolean = true): Color = when (this) {")
    for k, c in t["presetColor"].items():
        L.append(f"        {k.upper()} -> if (dark) {argb(c['dark'])} else {argb(c['light'])}")
    L.append("    }")
    L.append("")
    L.append("    fun onTile(dark: Boolean = true): Color = when (this) {")
    for k, c in t["presetColor"].items():
        o = c.get("onTile", {"dark": "#000000", "light": "#000000"})
        L.append(f"        {k.upper()} -> if (dark) {argb(o['dark'])} else {argb(o['light'])}")
    L.append("    }")
    L.append("")
    L.append("    companion object {")
    L.append("        fun of(name: String?): PresetColor = entries.firstOrNull { it.name.equals(name, ignoreCase = true) } ?: INK")
    L.append("    }")
    L.append("}")
    L.append("")

    L.append("/** Type scale (iOS text styles at their default size; Android scales them with the font-size setting). */")
    L.append("object CrateType {")
    for name, f in t["font"].items():
        if name == "tabLabel":
            continue
        family = "FontFamily.Monospace" if f["design"] == "monospaced" else "FontFamily.Default"
        extra = ""
        if f.get("monospacedDigit") or f["design"] == "rounded":
            extra += ", fontFeatureSettings = \"tnum\""
        if f.get("tracking"):
            extra += f", letterSpacing = {f['tracking']}.sp"
        L.append(f"    val {name} = TextStyle(fontSize = {f['size']}.sp, fontWeight = {WEIGHT[f['weight']]}, "
                 f"fontFamily = {family}{extra})")
    L.append("}")
    L.append("")

    def numbers(group: str, name: str, unit: str) -> None:
        vals = {k: v for k, v in t[group].items() if isinstance(v, (int, float))}
        L.append(f"object {name} {{")
        for k, v in vals.items():
            L.append(f"    val {k} = {v}.{unit}")
        L.append("}")
        L.append("")

    numbers("space", "Space", "dp")
    numbers("radius", "Radius", "dp")
    numbers("size", "Size", "dp")
    numbers("stroke", "Stroke", "dp")

    L.append("/** Default vibe symbols (SF Symbol names; `crateIcon()` maps them to Material icons). */")
    L.append("object VibeSymbols {")
    L.append("    val defaults: Map<String, String> = mapOf(")
    for k, v in t["vibe"]["defaults"].items():
        L.append(f"        \"{k}\" to \"{v}\",")
    L.append("    )")
    L.append("    val picker: List<String> = listOf(" + ", ".join(f'"{s}"' for s in t["vibe"]["pickerSymbols"]) + ")")
    sh = t["vibe"]["_rules"]["share"]
    L.append(f"    const val SHARE_TIGHT = {sh['tight']}")
    L.append(f"    const val SHARE_NORMAL = {sh['normal']}")
    L.append(f"    const val SHARE_WIDE = {sh['wide']}")
    L.append("}")
    L.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT.relative_to(ANDROID)}")


if __name__ == "__main__":
    main()
