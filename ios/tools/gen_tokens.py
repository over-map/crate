#!/usr/bin/env python3
"""Generate CrateUI/Tokens.generated.swift from ios/Design/tokens.json (the design handoff's source of truth).

Run after replacing tokens.json with a new design export:  python3 ios/tools/gen_tokens.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

IOS = Path(__file__).resolve().parents[1]
TOKENS = IOS / "Design" / "tokens.json"
OUT = IOS / "CrateKit" / "Sources" / "CrateUI" / "Tokens.generated.swift"


def hexlit(h: str) -> str:
    return "0x" + h.lstrip("#").upper()


def ident(family: str) -> str:
    parts = re.split(r"[^a-z0-9]+", family.lower())
    parts = [p for p in parts if p]
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def main() -> None:
    t = json.loads(TOKENS.read_text())
    L: list[str] = [
        "// Generated by ios/tools/gen_tokens.py from ios/Design/tokens.json. Do not edit by hand.",
        "// swiftlint:disable all",
        "import SwiftUI",
        "import CrateKit",
        "",
        "public extension Color {",
    ]
    for name, c in t["color"].items():
        L.append(f"    /// {c.get('use', '')}".rstrip())
        L.append(f"    static let {name} = Color.dynamic(dark: {hexlit(c['dark'])}, light: {hexlit(c['light'])})")
    L.append("}")
    L.append("")

    # Families
    fams = t["family"]
    L.append("/// The 17 style families (shown as \"Genre\" in the UI). Raw values are the data ids in library.json.")
    L.append("public enum Family: String, CaseIterable, Sendable, Identifiable {")
    for key in fams:
        if key.startswith("_") or not isinstance(fams[key], dict) or "shades" not in fams[key]:
            continue
        L.append(f"    case {ident(key)} = \"{fams[key]['data']}\"")
    L.append("    public var id: String { rawValue }")
    L.append("    /// UI name, sentence case.")
    L.append("    public var displayName: String {")
    L.append("        switch self {")
    for key, f in fams.items():
        if isinstance(f, dict) and "shades" in f:
            L.append(f"        case .{ident(key)}: \"{f['name']}\"")
    L.append("        }")
    L.append("    }")
    L.append("}")
    L.append("")
    L.append("public extension Color {")
    L.append("    /// Chip fill for a family in one of its three shades (StyleShade.of(style)).")
    L.append("    static func family(_ family: Family, shade: StyleShade = .base) -> Color {")
    L.append("        switch (family, shade) {")
    for key, f in fams.items():
        if not (isinstance(f, dict) and "shades" in f):
            continue
        for sh in ("light", "base", "deep"):
            s = f["shades"][sh]
            L.append(f"        case (.{ident(key)}, .{sh}): Color.dynamic(dark: {hexlit(s['dark'])}, light: {hexlit(s['light'])})")
    L.append("        }")
    L.append("    }")
    L.append("    /// Outline colour (removed style in Edit tags).")
    L.append("    static func familyOutline(_ family: Family) -> Color {")
    L.append("        switch family {")
    for key, f in fams.items():
        if isinstance(f, dict) and "shades" in f:
            o = f["outline"]
            L.append(f"        case .{ident(key)}: Color.dynamic(dark: {hexlit(o['dark'])}, light: {hexlit(o['light'])})")
    L.append("        }")
    L.append("    }")
    neutral = next((v for k, v in fams.items() if isinstance(v, dict) and "shades" not in v and ("dark" in v or "base" in v)), None)
    if neutral and "dark" in neutral:
        L.append(f"    /// Tracks with no family.")
        L.append(f"    static let familyNone = Color.dynamic(dark: {hexlit(neutral['dark'])}, light: {hexlit(neutral.get('light', neutral['dark']))})")
    else:
        L.append("    static let familyNone = Color(hex: 0xC5BBBD)")
    L.append("")
    L.append("    /// Energy meter colour for levels 1–10.")
    L.append("    static func energy(_ level: Int) -> Color {")
    L.append("        switch min(10, max(1, level)) {")
    for e in t["energy"]:
        L.append(f"        case {e['level']}: Color.dynamic(dark: {hexlit(e['dark'])}, light: {hexlit(e['light'])})")
    L.append("        default: .gray")
    L.append("        }")
    L.append("    }")
    L.append("")
    L.append("    /// Camelot badge fill (same in both modes). `code` like \"8A\".")
    L.append("    static func camelot(_ code: String) -> Color {")
    L.append("        switch code {")
    for code, c in t["camelot"].items():
        L.append(f"        case \"{code}\": Color.dynamic(dark: {hexlit(c['dark'])}, light: {hexlit(c['light'])})")
    L.append("        default: .gray")
    L.append("        }")
    L.append("    }")
    L.append("}")
    L.append("")

    # Preset colours
    L.append("public enum PresetColor: String, CaseIterable, Sendable {")
    for k in t["presetColor"]:
        L.append(f"    case {k}")
    L.append("    public var tile: Color {")
    L.append("        switch self {")
    for k, c in t["presetColor"].items():
        L.append(f"        case .{k}: Color.dynamic(dark: {hexlit(c['dark'])}, light: {hexlit(c['light'])})")
    L.append("        }")
    L.append("    }")
    L.append("    public var onTile: Color {")
    L.append("        switch self {")
    for k, c in t["presetColor"].items():
        o = c.get("onTile", {"dark": "#000000", "light": "#000000"})
        L.append(f"        case .{k}: Color.dynamic(dark: {hexlit(o['dark'])}, light: {hexlit(o['light'])})")
    L.append("        }")
    L.append("    }")
    L.append("}")
    L.append("")

    # Fonts
    weight = {"regular": ".regular", "medium": ".medium", "semibold": ".semibold", "bold": ".bold"}
    design = {"default": ".default", "rounded": ".rounded", "monospaced": ".monospaced"}
    style = {"largeTitle": ".largeTitle", "title": ".title", "title2": ".title2", "title3": ".title3", "headline": ".headline",
             "body": ".body", "subheadline": ".subheadline", "footnote": ".footnote", "caption2": ".caption2"}
    L.append("public extension Font {")
    defaults = {"largeTitle": 34, "title": 28, "title2": 22, "title3": 20, "headline": 17, "body": 17, "subheadline": 15,
                "footnote": 13, "caption2": 11}
    for name, f in t["font"].items():
        if name == "tabLabel" or name in ("headline", "body", "footnote"):  # identical to SwiftUI's own
            continue
        ts = f.get("relativeTo") or f.get("textStyle", "body")
        mono = ".monospacedDigit()" if f.get("monospacedDigit") else ""
        L.append(f"    /// {f['size']} pt {f['weight']} {f['design']}, scales with {ts}")
        if defaults.get(ts) == f["size"]:
            L.append(f"    static var {name}: Font {{ Font.system({style[ts]}, design: {design[f['design']]}, weight: {weight[f['weight']]}){mono} }}")
        else:
            cap = f.get("maxScale", 3.0)
            L.append(f"    static var {name}: Font {{ Font.system(size: CrateType.scaled({f['size']}, {style[ts]}, maxScale: {cap}), "
                     f"weight: {weight[f['weight']]}, design: {design[f['design']]}){mono} }}")
    L.append("}")
    L.append("")
    L.append("public extension View {")
    L.append("    /// Panel label style: SF Mono 11 semibold, uppercase, tracking 0.8, textSecondary.")
    L.append("    func panelLabelStyle() -> some View {")
    L.append("        font(.panelLabel).textCase(.uppercase).tracking(0.8).foregroundStyle(Color.textSecondary)")
    L.append("    }")
    L.append("}")
    L.append("")

    def numbers(group: str, typename: str) -> None:
        vals = {k: v for k, v in t[group].items() if isinstance(v, (int, float))}
        L.append(f"public enum {typename} {{")
        for k, v in vals.items():
            L.append(f"    public static let {k}: CGFloat = {v}")
        L.append("}")
        L.append("")

    numbers("space", "Space")
    numbers("radius", "Radius")
    numbers("size", "Size")
    numbers("stroke", "Stroke")

    # Vibe defaults
    L.append("public enum VibeSymbols {")
    L.append("    public static let defaults: [String: String] = [")
    for k, v in t["vibe"]["defaults"].items():
        L.append(f"        \"{k}\": \"{v}\",")
    L.append("    ]")
    L.append("    public static let picker: [String] = [" + ", ".join(f'"{s}"' for s in t["vibe"]["pickerSymbols"]) + "]")
    sh = t["vibe"]["_rules"]["share"]
    L.append(f"    public static let shareTight: Double = {sh['tight']}")
    L.append(f"    public static let shareNormal: Double = {sh['normal']}")
    L.append(f"    public static let shareWide: Double = {sh['wide']}")
    L.append("}")
    L.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT.relative_to(IOS)}")


if __name__ == "__main__":
    main()
